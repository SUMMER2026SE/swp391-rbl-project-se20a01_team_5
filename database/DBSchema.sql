CREATE OR REPLACE FUNCTION fn_validate_student_profile_role()
RETURNS TRIGGER AS $$
DECLARE
    actual_role VARCHAR(20);
BEGIN
    SELECT role INTO actual_role
    FROM users
    WHERE user_id = NEW.user_id;

    IF actual_role <> 'STUDENT' THEN
        RAISE EXCEPTION 'students.user_id must reference a STUDENT user, got %', actual_role;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validate_student_profile_role ON students;

CREATE TRIGGER trg_validate_student_profile_role
BEFORE INSERT OR UPDATE OF user_id ON students
FOR EACH ROW EXECUTE FUNCTION fn_validate_student_profile_role();

CREATE OR REPLACE FUNCTION fn_validate_staff_profile_role()
RETURNS TRIGGER AS $$
DECLARE
    actual_role VARCHAR(20);
BEGIN
    SELECT role INTO actual_role
    FROM users
    WHERE user_id = NEW.user_id;

    IF actual_role NOT IN ('DRIVER', 'CONDUCTOR', 'DISPATCHER') THEN
        RAISE EXCEPTION 'staff_profiles.user_id must reference staff user, got %', actual_role;
    END IF;

    IF actual_role = 'DRIVER' AND NEW.license_number IS NULL THEN
        RAISE EXCEPTION 'DRIVER staff profile requires license_number';
    END IF;

    IF actual_role IN ('CONDUCTOR', 'DISPATCHER') AND NEW.employee_code IS NULL THEN
        RAISE EXCEPTION 'CONDUCTOR/DISPATCHER staff profile requires employee_code';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validate_staff_profile_role ON staff_profiles;

CREATE TRIGGER trg_validate_staff_profile_role
BEFORE INSERT OR UPDATE OF user_id, employee_code, license_number ON staff_profiles
FOR EACH ROW EXECUTE FUNCTION fn_validate_staff_profile_role();

CREATE OR REPLACE FUNCTION fn_validate_schedule_staff_roles()
RETURNS TRIGGER AS $$
DECLARE
    driver_role VARCHAR(20);
    conductor_role VARCHAR(20);
BEGIN
    SELECT u.role INTO driver_role
    FROM staff_profiles sp
    JOIN users u ON u.user_id = sp.user_id
    WHERE sp.staff_id = NEW.driver_staff_id;

    IF driver_role <> 'DRIVER' THEN
        RAISE EXCEPTION 'bus_schedules.driver_staff_id must reference DRIVER staff';
    END IF;

    IF NEW.conductor_staff_id IS NOT NULL THEN
        SELECT u.role INTO conductor_role
        FROM staff_profiles sp
        JOIN users u ON u.user_id = sp.user_id
        WHERE sp.staff_id = NEW.conductor_staff_id;

        IF conductor_role <> 'CONDUCTOR' THEN
            RAISE EXCEPTION 'bus_schedules.conductor_staff_id must reference CONDUCTOR staff';
        END IF;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_validate_schedule_staff_roles ON bus_schedules;

CREATE TRIGGER trg_validate_schedule_staff_roles
BEFORE INSERT OR UPDATE OF driver_staff_id, conductor_staff_id ON bus_schedules
FOR EACH ROW EXECUTE FUNCTION fn_validate_schedule_staff_roles();

CREATE OR REPLACE FUNCTION fn_validate_driver_rating_role()
RETURNS TRIGGER AS $$
